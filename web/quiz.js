function getMaxUnits() {
  const g = quizState.activeGrade || '3上';
  const pub = (typeof window !== 'undefined' && window.activePublisher) ? window.activePublisher : (localStorage.getItem('kx_active_publisher') || 'kangxuan');
  if (pub === 'nanyi' || pub === 'hanlin') {
    if (g === '6上') return 8;
    if (g === '2上' || g === '4上' || g === '5上') return 10;
    return 9;
  }
  if (g === '2上' || g === '4上' || g === '5上') return 10;
  if (g === '1上' || g === '3上' || g === '6上') return 9;
  return 9;
}

function setQuizGrade(grade, skipRender = false) {
  if (quizState.activeGrade === grade) return;
  quizState.activeGrade = grade;
  quizState.currentUnit = 1;
  quizState.currentPaperIdx = 0;
  localStorage.setItem('kx_active_grade', grade);
  if (grade === '6上') {
    quizState.studentClass = '六年一班';
  } else if (grade === '5上') {
    quizState.studentClass = '五年一班';
  } else if (grade === '4上') {
    quizState.studentClass = '四年一班';
  } else if (grade === '3上') {
    quizState.studentClass = '三年一班';
  } else if (grade === '2上') {
    quizState.studentClass = '二年一班';
  } else if (grade === '1上') {
    quizState.studentClass = '一年一班';
  }
  if (!skipRender) {
    renderQuizCenter();
  }
}

function selectQuizUnit(u) {
  const maxU = getMaxUnits();
  if (u < 1 || u > maxU) u = 1;
  quizState.currentUnit = u;
  quizState.currentPaperIdx = 0;
  renderQuizCenter();
}

function selectQuizPaper(pIdx) {
  quizState.currentPaperIdx = pIdx;
  renderQuizCenter();
}

