function normalizeAnswer(str) {
  if (str === undefined || str === null) return '';
  return String(str)
    .trim()
    .replace(/[０-９]/g, s => String.fromCharCode(s.charCodeAt(0) - 0xFEE0))
    .replace(/又/g, ' ')       // 將口語「又」標準化為空格
    .replace(/\s+/g, ' ')     // 多個空白縮減為單一空白
    .trim()
    .replace(/(\d+)\s+(\d+\/\d+)/, '$1 $2'); // 確保帶分數統一為 "整數 分數" 格式
}

function gradeCurrentQuiz() {
  // 1. 強制身分驗證：確認當前使用者已登入且具備授權帳號
  const activeAuthUser = (typeof getActiveAuthUser === 'function')
    ? getActiveAuthUser()
    : ((window.authState && window.authState.user && window.authState.user.email) ? window.authState.user : null);

  if (!activeAuthUser || !activeAuthUser.email) {
    alert('⚠️ 尚未登入 Google 授權帳號！\n\n系統需要確認您的身分以登記測驗成績。\n請點擊右上角【Google 登入】並使用老師已開通授權的 Google 信箱，再行交卷！');
    if (typeof showLoginModal === 'function') {
      showLoginModal();
    }
    return;
  }

  saveStudentProfile();

  const currentUserEmail = activeAuthUser.email.toLowerCase().trim();
  const isAdmin = activeAuthUser.role === 'admin';

  if (!quizState.studentName || quizState.studentName === '小小數學家') {
    if (isAdmin) {
      quizState.studentName = (activeAuthUser.name || '系統管理員') + ' (試作)';
      quizState.studentClass = '管理員測試';
    } else {
      quizState.studentName = activeAuthUser.name || currentUserEmail.split('@')[0];
    }
    const nameInput = document.getElementById('quizStudentName');
    if (nameInput) nameInput.value = quizState.studentName;
    localStorage.setItem('kx_student_name', quizState.studentName);
  }

  const currentGrade = quizState.activeGrade || '3上';
  const u = quizState.currentUnit;
  const pIdx = quizState.currentPaperIdx;
  const bank = getActiveQuizBank();
  const titles = getActiveUnitTitles();
  const questions = (bank[u] && bank[u][pIdx]) ? bank[u][pIdx] : [];

  let score = 0;
  let correctCount = 0;
  const wrongQuestions = [];
  const questionsDetail = [];

  questions.forEach((item, qIdx) => {
    let userAns = '';
    if (item.type === 'mc' || item.type === 'tf') {
      const checked = document.querySelector(`input[name="q_${qIdx}"]:checked`);
      if (checked) userAns = checked.value;
    } else {
      const inp = document.getElementById(`q_input_${qIdx}`);
      if (inp) userAns = inp.value;
    }

    const isCorrect = normalizeAnswer(userAns) === normalizeAnswer(item.ans);
    if (isCorrect) {
      score += 20;
      correctCount++;
    } else {
      wrongQuestions.push({
        questionIdx: qIdx + 1,
        questionText: item.q || '',
        userAnswer: userAns || '(未作答)',
        correctAnswer: String(item.ans),
        explanation: item.explain || ''
      });
    }

    questionsDetail.push({
      questionIdx: qIdx + 1,
      questionText: item.q || '',
      userAnswer: userAns || '(未作答)',
      correctAnswer: String(item.ans),
      isCorrect: isCorrect,
      explanation: item.explain || ''
    });

    const card = document.getElementById(`q_card_${qIdx}`);
    const exp = document.getElementById(`q_explain_${qIdx}`);
    if (card && exp) {
      card.style.borderColor = isCorrect ? '#10B981' : '#EF4444';
      card.style.background = isCorrect ? '#F0FDF4' : '#FEF2F2';
      exp.style.display = 'block';
      exp.style.background = isCorrect ? '#DCFCE7' : '#FEE2E2';
      exp.style.color = isCorrect ? '#065F46' : '#991B1B';
      exp.innerHTML = isCorrect
        ? `✅ 答對了！（＋20 分） 💡 解析：${formatMath(item.explain)}`
        : `❌ 答錯了（你的答案：${formatMath(userAns) || '未作答'} ｜ 正確答案：<strong>${formatMath(item.ans)}</strong>）<br/>💡 訂正解析：${formatMath(item.explain)}`;
    }
  });

  // 儲存本地成績紀錄
  const now = new Date();
  const timeStr = `${now.getFullYear()}/${String(now.getMonth() + 1).padStart(2, '0')}/${String(now.getDate()).padStart(2, '0')} ${String(now.getHours()).padStart(2, '0')}:${String(now.getMinutes()).padStart(2, '0')}`;
  const rec = {
    time: timeStr,
    grade: currentGrade,
    email: currentUserEmail,
    studentClass: quizState.studentClass,
    seat: quizState.studentSeat,
    name: quizState.studentName,
    unit: u,
    unitTitle: titles[u],
    paperIdx: pIdx,
    paperName: paperTypes[pIdx].name,
    score,
    correctCount,
    wrongCount: wrongQuestions.length,
    questionsDetail: questionsDetail,
    isAdminAttempt: isAdmin
  };
  quizState.records.unshift(rec);
  localStorage.setItem('kx_quiz_records_all', JSON.stringify(quizState.records));
  localStorage.setItem('kx_g3_quiz_records', JSON.stringify(quizState.records));

  // 同步成績與錯題至 Cloudflare D1 資料庫
  fetch('/api/quiz/record', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      email: currentUserEmail,
      studentName: quizState.studentName,
      studentClass: quizState.studentClass,
      seatNum: quizState.studentSeat,
      grade: currentGrade,
      unit: u,
      paperIdx: pIdx,
      paperName: paperTypes[pIdx].name,
      score,
      correctCount,
      totalCount: 5,
      timeSpentSec: 0,
      wrongQuestions,
      questionsDetail
    })
  }).then(res => {
    if (res.status === 403) {
      return res.json().then(errData => {
        alert(`🚫 雲端資料庫拒絕記錄：\n${errData.error || '您的帳號未在授權名單中或已被管理員移除！'}`);
      });
    }
    return res.json().then(data => {
      if (data && data.success) {
        console.log('✅ 成績與錯題已成功同步至 Cloudflare D1:', data);
      }
    });
  }).catch(err => {
    console.warn('D1 雲端同步提示 (離線或本地):', err);
  });

  // 更新分數徽章與鼓勵語
  const badge = document.getElementById('quizLiveScoreBadge');
  if (badge) {
    badge.textContent = `得分：${score} 分`;
    badge.style.color = score >= 80 ? '#059669' : score >= 60 ? '#D97706' : '#DC2626';
  }

  const banner = document.getElementById('quizSummaryBanner');
  if (banner) {
    banner.style.display = 'flex';
    banner.className = score >= 80 ? 'feedback-banner success' : 'feedback-banner warning';
    const comment = score === 100
      ? '🏆 太神啦！滿分 100 分！完全掌握這個單元的觀念！'
      : score >= 80
      ? '🎉 表現優異！只差一點點就滿分囉，看看上方紅色題目的訂正解析吧！'
      : '💪 再接再厲！先閱讀每一題下方的訂正解析，系統已記錄錯題供日後補救練習！';
    const d1Note = `<span style="font-size:0.8rem; background:#EDE9FE; color:#6D28D9; padding:0.2rem 0.5rem; border-radius:99px; margin-left:0.5rem; font-weight:700;">☁️ D1已記錄 (${currentUserEmail})</span>`;
    banner.innerHTML = `📝 批改完成！<strong>${quizState.studentClass} ${quizState.studentSeat}號 ${quizState.studentName}</strong> 在【${titles[u]} - ${paperTypes[pIdx].name}】答對 <strong>${correctCount}/5 題</strong>，總分：<strong>${score} 分</strong>！${comment} ${d1Note}`;
  }

  const sbWrap = document.getElementById('quizScoreboardWrap');
  if (sbWrap) sbWrap.innerHTML = renderScoreboardTable();

  if (score >= 60) addStar(Math.floor(score / 20));
  else playTone(330, 0.15);
}

